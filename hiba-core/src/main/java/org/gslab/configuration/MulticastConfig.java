package org.gslab.configuration;

public class MulticastConfig {

    private int initMCASTFrequency;
    private int initMCASTTimeInterval;
    private int highestScoreMCASTFrequency;
    private int highestScoreMCASTTimeInterval;
    private int isBrokerMCASTFrequency;
    private int isBrokerMCASTTimeInterval;

    public int getInitMCASTFrequency() {
        return initMCASTFrequency;
    }

    public void setInitMCASTFrequency(int initMCASTFrequency) {
        this.initMCASTFrequency = initMCASTFrequency;
    }

    public int getInitMCASTTimeInterval() {
        return initMCASTTimeInterval;
    }

    public void setInitMCASTTimeInterval(int initMCASTTimeInterval) {
        this.initMCASTTimeInterval = initMCASTTimeInterval;
    }

    public int getHighestScoreMCASTFrequency() {
        return highestScoreMCASTFrequency;
    }

    public void setHighestScoreMCASTFrequency(int highestScoreMCASTFrequency) {
        this.highestScoreMCASTFrequency = highestScoreMCASTFrequency;
    }

    public int getHighestScoreMCASTTimeInterval() {
        return highestScoreMCASTTimeInterval;
    }

    public void setHighestScoreMCASTTimeInterval(int highestScoreMCASTTimeInterval) {
        this.highestScoreMCASTTimeInterval = highestScoreMCASTTimeInterval;
    }

    public int getIsBrokerMCASTFrequency() {
        return isBrokerMCASTFrequency;
    }

    public void setIsBrokerMCASTFrequency(int isBrokerMCASTFrequency) {
        this.isBrokerMCASTFrequency = isBrokerMCASTFrequency;
    }

    public int getIsBrokerMCASTTimeInterval() {
        return isBrokerMCASTTimeInterval;
    }

    public void setIsBrokerMCASTTimeInterval(int isBrokerMCASTTimeInterval) {
        this.isBrokerMCASTTimeInterval = isBrokerMCASTTimeInterval;
    }
}
